#!/usr/bin/env python3
"""Generate the fused-upsample (_fu) candidates of the four bottom families from their _wq reference kernels.

Only the activation fetch changes: every read of the materialised upsampled tensor (`ups`) becomes the connected
bilinear formula evaluated at the point of use on the low-resolution source (fu_upsample.metalh). The fast pass,
certificate, fold, flags, repair passes and epilogues are copied verbatim. The _wq reference files are read, never
written. Each substitution must match its anchor exactly the expected number of times, and the output must not
mention `ups` anywhere, or generation fails.

    python3 src/fg_conv/make_fu.py
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent


def sub(text, old, new, count, what):
    found = text.count(old)
    if found != count:
        raise SystemExit(f'{what}: anchor found {found} times, expected {count}: {old[:80]!r}')
    return text.replace(old, new)


def cut(text, start, end, what):
    """Remove text from `start` (inclusive) up to `end` (exclusive); both anchors unique."""
    if text.count(start) != 1 or text.count(end) != 1:
        raise SystemExit(f'{what}: cut anchors not unique')
    i, j = text.index(start), text.index(end)
    if j <= i:
        raise SystemExit(f'{what}: cut anchors out of order')
    return text[:i] + text[j:]


def header(text, family, launch, src_dims):
    note = (f'// _fu: fused bilinear fetch candidate for {family} (launch {launch}), generated by make_fu.py from the _wq file.\n'
            f'// The convolution computes each upsampled operand from the {src_dims} source (fu_upsample.metalh, the connected\n'
            '// RTX formula) instead of reading the materialised tensor; no upsample dispatch, no upsampled buffer. Every\n'
            '// other line is the _wq kernel verbatim under an _fu name. Optional candidate; the _wq files stay the reference.\n\n')
    text = sub(text, '#include "hmma_exact_u32.metalh"\n',
               '#include "hmma_exact_u32.metalh"\n#include "fu_upsample.metalh"\n', 1, family + ' include')
    return note + text


def finish(text, family, kernels):
    for k in kernels:
        text = sub(text, f'{k}_wq(', f'{k}_fu(', 1, family + ' rename ' + k)
    code = '\n'.join(line.split('//', 1)[0] for line in text.splitlines())   # design notes may mention ups
    left = re.search(r'[^\n]*\bups[0-2]?\b[^\n]*', code)
    if left:
        raise SystemExit(f'{family}: materialised-tensor reference left: {left.group(0)!r}')
    if re.search(r'kernel void \w+_wq\(', text):   # inline helpers such as load_b_wq keep their names
        raise SystemExit(f'{family}: unrenamed _wq kernel left')
    return text


def bot0_like(src_name, out_name, family, launch, OW, OH, SW, SH, C, stages, prefix, stage_fn):
    text = (HERE / src_name).read_text()
    text = header(text, family, launch, f'{SW}x{SH}x{C}')
    # the old two-rounding up() and its unused materialising kernel (the runtime uses connected_upsamples.metal)
    text = cut(text, 'inline half up(', 'inline uint wi(', family + ' up()')
    text = cut(text, f'// --- upsample:', 'inline void scatter(', family + ' upsample kernel')
    text = sub(text, 'device const half* ups [[buffer(2)]]', 'device const half* src [[buffer(2)]]', 3, family + ' buffer')
    # fast pass: tap geometry once per tap, both columns of a lane per (stage, kb) as one half2 fetch
    text = sub(text, f'    const uint base = ok ? (uint(iy) * {OW}u + uint(ix)) * {C}u : 0u;\n',
               f'    const FuTap T = fu_tap(ok, ix, iy, {SW}u, {SH}u, {C}u);\n', 1, family + ' fast tap')
    text = sub(text,
               '      for (uint kb = 0u; kb < 2u; ++kb) {\n'
               '#pragma clang loop unroll(full)\n'
               '        for (uint h = 0u; h < 2u; ++h) {\n'
               '          const float av = ok ? float(ups[base + s * 16u + kb * 8u + mc + h]) : 0.0f;\n',
               '      for (uint kb = 0u; kb < 2u; ++kb) {\n'
               '        const half2 fv = fu_fetch2(src, T, s * 16u + kb * 8u + mc);\n'
               '#pragma clang loop unroll(full)\n'
               '        for (uint h = 0u; h < 2u; ++h) {\n'
               '          const float av = ok ? float(fv[h]) : 0.0f;\n', 1, family + ' fast fetch')
    # exact stage: sixteen operands as four half4 fetches
    text = sub(text, f'inline half {stage_fn}(device const half* w, device const half* ups,',
               f'inline half {stage_fn}(device const half* w, device const half* src,', 1, family + ' stage signature')
    text = sub(text, f'  const uint base = ok ? (uint(y) * {OW}u + uint(x)) * {C}u : 0u;\n  ushort av[16], bv[16];\n',
               '  ushort av[16], bv[16];\n', 1, family + ' stage base')
    if stage_fn == 'bot0_stage':
        old_load = ('    device const half* row = ups + base + s * 16u;\n'
                    '    const ushort4 v0 = *reinterpret_cast<device const ushort4*>(row), v1 = *reinterpret_cast<device const ushort4*>(row + 4u),\n'
                    '                  v2 = *reinterpret_cast<device const ushort4*>(row + 8u), v3 = *reinterpret_cast<device const ushort4*>(row + 12u);\n')
    else:
        old_load = ('    // ups rows are 32 halves (64 B); stage s starts at half offset base + 16 s, i.e. 32 B aligned.\n'
                    '    device const ushort4* v = reinterpret_cast<device const ushort4*>(ups + base + s * 16u);\n'
                    '    const ushort4 v0 = v[0], v1 = v[1], v2 = v[2], v3 = v[3];\n')
    new_load = (f'    const FuTap T = fu_tap(true, x, y, {SW}u, {SH}u, {C}u);\n'
                '    const ushort4 v0 = as_type<ushort4>(fu_fetch4(src, T, s * 16u)), v1 = as_type<ushort4>(fu_fetch4(src, T, s * 16u + 4u)),\n'
                '                  v2 = as_type<ushort4>(fu_fetch4(src, T, s * 16u + 8u)), v3 = as_type<ushort4>(fu_fetch4(src, T, s * 16u + 12u));\n')
    text = sub(text, old_load, new_load, 1, family + ' stage load')
    text = sub(text, f'{stage_fn}(w, ups, ', f'{stage_fn}(w, src, ', 3, family + ' stage calls')
    text = finish(text, family, [f'{prefix}_bounded', f'{prefix}_repair_pass1', f'{prefix}_listed'])
    (HERE / out_name).write_text(text)


def bot1_like(src_name, out_name, family, launch, OW, OH, SW, SH, C, staged, prefix, stage_fn, planar_kernel):
    text = (HERE / src_name).read_text()
    text = header(text, family, launch, f'{SW}x{SH}x{C} (three planes)')
    text = cut(text, 'inline half up(', 'inline uint wi(', family + ' up()')
    text = cut(text, f'kernel void {prefix}_upsample_wq(', '// One guarded stage for one plane', family + ' upsample kernel')
    # the per-plane A/B variant reads the materialised tensor through load_a; the runtime never dispatches it
    text = cut(text, '// --- fast pass, design six numerics, one dispatch per plane', '// --- one exact ', family + ' planar kernel')
    s_term = 's * 16u + ' if staged else ''
    text = sub(text,
               'inline void load_a(thread simdgroup_float8x8* a, thread simdgroup_float8x8* qa, device const half* ups, uint base, bool ok, ' + ('uint s, ' if staged else '') + 'uint mc) {\n'
               '#pragma clang loop unroll(full)\n'
               '  for (uint kb = 0u; kb < 2u; ++kb)\n'
               '#pragma clang loop unroll(full)\n'
               '    for (uint h = 0u; h < 2u; ++h) {\n'
               f'      const float av = ok ? float(ups[base + {s_term}kb * 8u + mc + h]) : 0.0f;\n'
               '      a[kb].thread_elements()[h] = av; qa[kb].thread_elements()[h] = FORMAL ? bound_operand(av) : fabs(av);\n'
               '    }\n'
               '}\n',
               'inline void load_a(thread simdgroup_float8x8* a, thread simdgroup_float8x8* qa, device const half* src, thread const FuTap& T, bool ok, ' + ('uint s, ' if staged else '') + 'uint mc) {\n'
               '#pragma clang loop unroll(full)\n'
               '  for (uint kb = 0u; kb < 2u; ++kb) {\n'
               f'    const half2 fv = fu_fetch2(src, T, {s_term}kb * 8u + mc);\n'
               '#pragma clang loop unroll(full)\n'
               '    for (uint h = 0u; h < 2u; ++h) {\n'
               '      const float av = ok ? float(fv[h]) : 0.0f;\n'
               '      a[kb].thread_elements()[h] = av; qa[kb].thread_elements()[h] = FORMAL ? bound_operand(av) : fabs(av);\n'
               '    }\n'
               '  }\n'
               '}\n', 1, family + ' load_a')
    text = sub(text,
               '    device const half* ups0 [[buffer(2)]], device const half* ups1 [[buffer(3)]], device const half* ups2 [[buffer(4)]],',
               '    device const half* src0 [[buffer(2)]], device const half* src1 [[buffer(3)]], device const half* src2 [[buffer(4)]],',
               3, family + ' buffers')
    text = sub(text, f'    const uint base = ok ? (uint(iy) * {OW}u + uint(ix)) * {C}u : 0u;\n',
               f'    const FuTap T = fu_tap(ok, ix, iy, {SW}u, {SH}u, {C}u);\n', 1, family + ' fast tap')
    indent = '        ' if staged else '      '
    text = sub(text, f'{indent}device const half* ups = p == 0u ? ups0 : (p == 1u ? ups1 : ups2);\n',
               f'{indent}device const half* src = p == 0u ? src0 : (p == 1u ? src1 : src2);\n', 1, family + ' plane select')
    text = sub(text, 'load_a(a, qa, ups, base, ok, ' + ('s, ' if staged else '') + 'mc);',
               'load_a(a, qa, src, T, ok, ' + ('s, ' if staged else '') + 'mc);', 1, family + ' load_a call')
    # exact stage (pass 1)
    text = sub(text, f'inline half {stage_fn}(device const half* w, device const half* ups,',
               f'inline half {stage_fn}(device const half* w, device const half* src,', 1, family + ' stage signature')
    text = sub(text, f'  const uint base = ok ? (uint(y) * {OW}u + uint(x)) * {C}u : 0u;\n  ushort av[16], bv[16];\n',
               '  ushort av[16], bv[16];\n', 1, family + ' stage base')
    if staged:
        old_load = ('    // ups rows are 32 halves (64 B); stage s starts at half offset base + 16 s, i.e. 32 B aligned.\n'
                    '    device const ushort4* v = reinterpret_cast<device const ushort4*>(ups + base + s * 16u);\n'
                    '    const ushort4 v0 = v[0], v1 = v[1], v2 = v[2], v3 = v[3];\n')
        off = 's * 16u'
    else:
        old_load = ('    // ups rows are 16 halves (32 B); a tap covers the whole row, so the start is 32 B aligned.\n'
                    '    device const ushort4* v = reinterpret_cast<device const ushort4*>(ups + base);\n'
                    '    const ushort4 v0 = v[0], v1 = v[1], v2 = v[2], v3 = v[3];\n')
        off = '0u'
    new_load = (f'    const FuTap T = fu_tap(true, x, y, {SW}u, {SH}u, {C}u);\n'
                f'    const ushort4 v0 = as_type<ushort4>(fu_fetch4(src, T, {off})), v1 = as_type<ushort4>(fu_fetch4(src, T, {off} + 4u)),\n'
                f'                  v2 = as_type<ushort4>(fu_fetch4(src, T, {off} + 8u)), v3 = as_type<ushort4>(fu_fetch4(src, T, {off} + 12u));\n')
    text = sub(text, old_load, new_load, 1, family + ' stage load')
    # lane-parallel exact stage (pass 2): one operand per lane
    text = sub(text, f'inline half {stage_fn}_lanes(device const half* w, device const half* ups,',
               f'inline half {stage_fn}_lanes(device const half* w, device const half* src,', 1, family + ' lanes signature')
    if staged:
        old_lane = (f'  const uint base = ok ? (uint(y) * {OW}u + uint(x)) * {C}u : 0u;\n'
                    '  const uint ic = s * 16u + k;\n'
                    '  const ushort av = ok ? as_type<ushort>(ups[base + ic]) : ushort(0);\n')
        new_lane = ('  const uint ic = s * 16u + k;\n'
                    f'  const ushort av = ok ? as_type<ushort>(fu_fetch1(src, fu_tap(ok, x, y, {SW}u, {SH}u, {C}u), ic)) : ushort(0);\n')
    else:
        old_lane = (f'  const uint base = ok ? (uint(y) * {OW}u + uint(x)) * {C}u : 0u;\n'
                    '  const ushort av = ok ? as_type<ushort>(ups[base + k]) : ushort(0);\n')
        new_lane = f'  const ushort av = ok ? as_type<ushort>(fu_fetch1(src, fu_tap(ok, x, y, {SW}u, {SH}u, {C}u), k)) : ushort(0);\n'
    text = sub(text, old_lane, new_lane, 1, family + ' lanes load')
    # plane selection in the listed kernels
    text = sub(text, '  device const half* ups = oc < 4u ? ups0 : (oc == 4u ? ups1 : ups2);\n',
               '  device const half* src = oc < 4u ? src0 : (oc == 4u ? src1 : src2);\n', 2, family + ' listed plane select')
    text = sub(text, f'{stage_fn}(w, ups, ', f'{stage_fn}(w, src, ', 2, family + ' stage calls')
    text = sub(text, f'{stage_fn}_lanes(w, ups, ', f'{stage_fn}_lanes(w, src, ', 1, family + ' lanes call')
    text = finish(text, family, [f'{prefix}_bounded', f'{prefix}_repair_pass1', f'{prefix}_listed'])
    (HERE / out_name).write_text(text)


