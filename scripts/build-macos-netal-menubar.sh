#!/bin/zsh
# Build the Netal menu-bar app: a status item showing runtime state and basic metrics, with an
# on/off toggle that drives the runtime's pause marker.
#   scripts/build-macos-netal-menubar.sh [--run]
set -euo pipefail
script_dir="$(cd "$(dirname "$0")" && pwd)"; repository="$(cd "$script_dir/.." && pwd)"
source_dir="$repository/src/macos_app/NetalMenuBar"
out="$repository/build/netal-menubar"
app="$out/Netal.app"
run=0
[[ "${1:-}" == "--run" ]] && run=1
app_version="${NETAL_APP_VERSION:-0.1.0}"
app_build="${NETAL_APP_BUILD:-1}"
release_channel="${NETAL_RELEASE_CHANNEL:-source-preview}"
[[ "$app_version" =~ '^[0-9]+\.[0-9]+\.[0-9]+$' ]] || { print -u2 'Invalid NETAL_APP_VERSION'; exit 1; }
[[ "$app_build" =~ '^[0-9]+$' ]] || { print -u2 'Invalid NETAL_APP_BUILD'; exit 1; }
[[ "$release_channel" =~ '^[a-z0-9-]+$' ]] || { print -u2 'Invalid NETAL_RELEASE_CHANNEL'; exit 1; }

rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources" "$out"

# Runtime paths are resolved at launch by NetalBuildDefaults.swift.
cat > "$app/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Netal</string>
  <key>CFBundleDisplayName</key><string>Netal</string>
  <key>CFBundleIdentifier</key><string>com.nschlaepfer.netal.menubar</string>
  <key>CFBundleExecutable</key><string>Netal</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$app_version</string>
  <key>NetalReleaseChannel</key><string>$release_channel</string>
  <key>CFBundleVersion</key><string>$app_build</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <!-- Menu-bar only: no Dock tile, no main window. -->
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSScreenCaptureUsageDescription</key><string>Netal captures only the game window you select to upscale and interpolate it locally.</string>
</dict>
</plist>
PLIST

# App icon from the brand assets, if iconutil is available.
# Generated by tools/netal-appicon.swift: the brand mark on the rounded-rect body macOS expects,
# rather than the raw render on an opaque white square, which reads as a white tile in the Dock.
icon_src="$out/NetalAppIcon.png"
[[ ! -f "$repository/docs/brand/netal-appicon.png" ]] || cp "$repository/docs/brand/netal-appicon.png" "$icon_src"
if [[ -f "$source_dir/Resources/NetalChrome.png" ]]; then
  cp "$source_dir/Resources/NetalChrome.png" "$icon_src"
elif [[ -f "$repository/src/macos_app/NetalMenuBar/Resources/NetalMark.png" ]] && command -v swift >/dev/null 2>&1; then
  swift "$repository/tools/netal-appicon.swift" \
    "$repository/src/macos_app/NetalMenuBar/Resources/NetalMark.png" "$icon_src" >/dev/null 2>&1 || true
fi
if [[ -f "$icon_src" ]] && command -v iconutil >/dev/null 2>&1; then
  iconset="$out/AppIcon.iconset"; rm -rf "$iconset"; mkdir -p "$iconset"
  for size in 16 32 128 256 512; do
    sips -z $size $size "$icon_src" --out "$iconset/icon_${size}x${size}.png" >/dev/null 2>&1 || true
    sips -z $((size * 2)) $((size * 2)) "$icon_src" --out "$iconset/icon_${size}x${size}@2x.png" >/dev/null 2>&1 || true
  done
  iconutil -c icns "$iconset" -o "$app/Contents/Resources/AppIcon.icns" 2>/dev/null || true
  rm -rf "$iconset"
fi

# Artwork the app loads by name: the lifted-subject mark for About, and the menu-bar template.
# Generated from docs/brand by tools/netal-cutout.swift; regenerate with:
#   build/tools/netal-cutout docs/brand/netal-icon.png <mark> <template>
if [[ -d "$source_dir/Resources" ]]; then
  # Everything in Resources, not just images: the sprite tool also emits the measured eye
  # positions as JSON, and copying by extension silently left them out.
  cp "$source_dir/Resources"/* "$app/Contents/Resources/" 2>/dev/null || true
fi

# Supported FG identities are app resources, independent of the selected runtime.
cp "$repository/src/fg_runtime/runtime-inputs.json" "$app/Contents/Resources/FGRuntimeInputs.json"

# The Command Line Tools' swiftc has no SwiftUI macro plugin, and against the macOS 27 SDK
# SwiftUI's @State is a macro - so the build dies with "SwiftUIMacros not found" whenever the
# default SDK is 27 and no Xcode is installed. The macOS 26 SDK builds the same app (target is
# macOS 14 either way), so prefer it unless the caller pinned SDKROOT.
if [[ -z "${SDKROOT:-}" ]]; then
  for candidate in /Library/Developer/CommandLineTools/SDKs/MacOSX26.sdk; do
    [[ -d "$candidate" ]] && export SDKROOT="$candidate" && break
  done
fi

swiftc \
  -O -swift-version 5 \
  -file-prefix-map "$repository=." -debug-prefix-map "$repository=." \
  -file-compilation-dir . \
  -import-objc-header "$source_dir/NetalProcessInfo.h" \
  -target arm64-apple-macos14.0 \
  -framework SwiftUI -framework AppKit -framework Combine \
  -framework ScreenCaptureKit -framework Metal -framework MetalFX -framework MetalKit \
  -framework CoreVideo -framework CoreMedia -framework Carbon \
  "$source_dir"/*.swift \
  -o "$app/Contents/MacOS/Netal"

# Source builds use local ad-hoc signing; release signing is a separate workflow.
codesign --force --sign - "$app"
print "signed=ad-hoc (source build)"

print "built=$app"
print "runtime=resolved at launch (NETAL_RUNTIME_ROOT or Settings)"
print "run: open \"$app\"   (override the log with: defaults write com.nschlaepfer.netal.menubar NetalLogPath <path>)"

if (( run )); then
  pkill -f "$app/Contents/MacOS/Netal" 2>/dev/null || true
  open "$app"
fi
